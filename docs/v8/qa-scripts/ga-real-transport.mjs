import { chromium } from 'playwright';
const BASE = process.env.QA_BASE || 'http://localhost:3201';
const ID = 'G-0DJ220E3ZL';
const b = await chromium.launch({channel:'chrome'});
const c = await b.newContext({viewport:{width:390,height:844}});
const p=await c.newPage();
const hits=[];
p.on('request',r=>{if(/googletagmanager\.com|google-analytics\.com/.test(r.url()))hits.push({url:r.url(),body:r.postData()||'',status:0})});
p.on('response',r=>{const h=hits.find(x=>x.url===r.url());if(h)h.status=r.status()});
await p.goto(BASE,{waitUntil:'networkidle'});
await p.waitForTimeout(400);
const clean=hits.length===0;
console.log('REAL_NO_GOOGLE_BEFORE_CONSENT',clean?'PASS':'FAIL');
await p.getByRole('button',{name:/Permitir medici/}).click();
await p.waitForTimeout(4500);
const tag=hits.some(h=>h.url.includes('/gtag/js?id='+ID) && h.status===200);
const gaHits=()=>hits.filter(h=>/google-analytics\.com\/g\/collect/.test(h.url));
const hasEvent=(h,n)=>new URL(h.url).searchParams.get('en')===n || new URLSearchParams(h.body).get('en')===n || h.body.includes('en='+n);
const pageview=gaHits().some(h=>new URL(h.url).searchParams.get('tid')===ID && hasEvent(h,'page_view'));
console.log('REAL_TAG_LOADED',tag?'PASS':'FAIL');
console.log('REAL_PAGEVIEW_SENT',pageview?'PASS':'FAIL');
await p.evaluate(() => document.querySelectorAll('a[href^="https://wa.me/"]').forEach(a=>a.addEventListener('click',e=>e.preventDefault())));
await p.locator('main a[href^="https://wa.me/"]').first().click({force:true});
await p.waitForTimeout(15500);
const custom=gaHits().find(h=>new URL(h.url).searchParams.get('tid')===ID && hasEvent(h,'whatsapp_click'));
const safe=custom && !/528333263389|wa\.me|Hola%20|text=|phone_number/.test(decodeURIComponent(custom.url+'\n'+custom.body));
console.log('REAL_WHATSAPP_EVENT_SENT',custom?'PASS':'FAIL');
console.log('REAL_EVENT_NO_PHONE_OR_MESSAGE',safe?'PASS':'FAIL');
console.log('GOOGLE_NETWORK_QA_COUNTS',{requests:hits.length,collects:gaHits().length});
await c.close();await b.close();
if(!clean||!tag||!pageview||!custom||!safe)process.exit(1);
