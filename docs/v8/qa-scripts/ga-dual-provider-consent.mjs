import { chromium } from 'playwright';
const BASE=process.env.QA_BASE||'https://www.lsslocalsystemsstudio.com';
const b=await chromium.launch({channel:'chrome'});
const reqs=[];
const c=await b.newContext({viewport:{width:390,height:844}});
const p=await c.newPage();
p.on('request',r=>{if(/googletagmanager\.com|google-analytics\.com|connect\.facebook\.net|facebook\.com\/tr/.test(r.url()))reqs.push(r.url())});
await p.goto(BASE,{waitUntil:'networkidle'});await p.waitForTimeout(600);
const empty=reqs.length===0;
const text=await p.locator('.privacy-consent').innerText();
const disclosed=text.includes('Google Analytics')&&text.includes('Meta');
console.log('BOTH_PROVIDERS_BLOCKED_PRECONSENT',empty?'PASS':'FAIL');
console.log('BOTH_PURPOSES_DISCLOSED',disclosed?'PASS':'FAIL');
await p.getByRole('button',{name:/^Rechazar(?: medici.n)?$/}).click();
await p.reload({waitUntil:'networkidle'});await p.waitForTimeout(500);
const reject=reqs.length===0;
console.log('REJECT_BLOCKS_BOTH',reject?'PASS':'FAIL');
await c.close();
const c2=await b.newContext({viewport:{width:390,height:844}});
const p2=await c2.newPage();const attempted=[];
p2.on('request',r=>{if(/googletagmanager\.com|google-analytics\.com|connect\.facebook\.net|facebook\.com\/tr/.test(r.url()))attempted.push(r.url())});
await p2.goto(BASE,{waitUntil:'networkidle'});await p2.getByRole('button',{name:/^Permitir(?: medici.n)?$/}).click();await p2.waitForTimeout(4500);
const google=attempted.some(u=>u.includes('/gtag/js?id=G-0DJ220E3ZL'));
const meta=attempted.some(u=>u.includes('connect.facebook.net/en_US/fbevents.js'));
console.log('CONSENT_ENABLES_GA4',google?'PASS':'FAIL');
console.log('CONSENT_ENABLES_META',meta?'PASS':'FAIL');
await c2.close();await b.close();if(!empty||!disclosed||!reject||!google||!meta)process.exit(1);
